/**
 * Normalizes input text: converts Hindi characters to transliterated English/Hinglish keys,
 * collapses whitespace, and lowercases.
 */
export function normalizeSearchQuery(query: string): string {
  if (!query) return ''
  let cleaned = query.trim().toLowerCase()
  
  for (const [hindi, eng] of Object.entries(HINDI_DEVANAGARI_MAP)) {
    if (cleaned.includes(hindi)) {
      cleaned = cleaned.replace(new RegExp(hindi, 'g'), ` ${eng} `)
    }
  }

  return cleaned.replace(/\s+/g, ' ').trim()
}

